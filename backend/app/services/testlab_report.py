def _safe_xml(val: Any, limit: Optional[int] = None) -> str:
    """Safely escapes strings for ReportLab XML/HTML Paragraph elements."""
    if val is None:
        return ""
    s = str(val)
    if limit and len(s) > limit:
        s = s[:limit] + "..."
    return html.escape(s)

